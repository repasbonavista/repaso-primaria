const orderNames = {100:'centenes',1000:'unitats de miler',10000:'desenes de miler',100000:'centenes de miler',1000000:'unitats de milió'};
export const formatMathNumber = number => String(number).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
export function buildRoundingQuestions() {
  const pool = [...roundingBank];
  for (let i = pool.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [pool[i],pool[j]] = [pool[j],pool[i]]; }
  return pool.slice(0,10).map(([number,order]) => {
    const answer = Math.floor((number + order / 2) / order) * order;
    const nextDigit = Math.floor(number / (order / 10)) % 10;
    return { question: `Aproxima ${formatMathNumber(number)} a les ${orderNames[order]}.`, answer,
      explanation: `La xifra següent és ${nextDigit}. ${nextDigit < 5 ? 'És menor que 5: mantenim l’ordre triat' : 'És 5 o més: augmentem en una unitat l’ordre triat'} i posem zeros a la dreta. Resultat: ${formatMathNumber(answer)}.` };
  });
}
